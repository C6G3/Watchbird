// Applies the migration to a replica of the ORIGINAL live schema (legacy
// "Devices"/"Data" with bigint ids, open anon policies, existing rows), twice,
// and to a fresh database, then checks data survives and anon is locked out.
// Run: npm --prefix supabase/tests test
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";

const migration = readFileSync(process.argv[2] ?? new URL("../migrations/20261103000000_init.sql", import.meta.url), "utf8");
const STUBS = `
  create role anon; create role authenticated; create role service_role bypassrls;
  grant usage on schema public to anon, authenticated, service_role;
  alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
  alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
  create schema auth;
  create table auth.users (id uuid primary key, email text, raw_user_meta_data jsonb);
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema auth to anon, authenticated, service_role;
  create schema storage;
  create table storage.buckets (id text primary key, name text, public boolean);
  create table storage.objects (id serial primary key, bucket_id text, name text);
  alter table storage.objects enable row level security;
  create function storage.foldername(name text) returns text[] language sql as $$ select string_to_array(name, '/') $$;
  create publication supabase_realtime;
`;
// The Streamlit-era project, per the old README, with open anon policies.
const LEGACY = `
  CREATE TABLE public."Devices" ("Device_id" BIGINT PRIMARY KEY, "Device_name" TEXT NOT NULL UNIQUE, "Status" TEXT, "Created_at" TIMESTAMPTZ DEFAULT now(),
    "Color_1" TEXT, "Color_2" TEXT, "IF_model" TEXT);
  CREATE TABLE public."Data" ("Id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Device_id" BIGINT REFERENCES public."Devices"("Device_id"), "Timestamp" TIMESTAMPTZ NOT NULL,
    "Latitude" FLOAT NOT NULL, "Longitude" FLOAT NOT NULL, "Altitude" FLOAT, speed_m_s FLOAT, delta_alt FLOAT,
    dt FLOAT, distance_m FLOAT, bearing FLOAT, acceleration FLOAT, "Anomaly" INT DEFAULT 1);
  CREATE INDEX ON public."Data" ("Device_id", "Timestamp" DESC);
  ALTER TABLE public."Data" ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public."Devices" ENABLE ROW LEVEL SECURITY;
  CREATE POLICY "Enable read access for all users" ON public."Data" FOR SELECT USING (true);
  CREATE POLICY "anon insert" ON public."Data" FOR INSERT TO anon WITH CHECK (true);
  CREATE POLICY "anon all devices" ON public."Devices" FOR ALL USING (true) WITH CHECK (true);
  ALTER PUBLICATION supabase_realtime ADD TABLE public."Data";
  INSERT INTO public."Devices" ("Device_id","Device_name","Status","Color_1","Color_2","IF_model") VALUES (1,'wb_1','Active ','#FF0000','#FF0000','wb_1'), (3,'wb_3','Active','blue','blue',NULL);
  INSERT INTO public."Data" ("Device_id","Timestamp","Latitude","Longitude","Altitude","Anomaly")
    VALUES (1, now(), -0.4, 36.9, 1800, 1), (3, now(), -1.26, 36.84, 1868, -1);
  INSERT INTO auth.users VALUES ('00000000-0000-0000-0000-0000000000aa','old@x.io','{"full_name":"Early User"}');
`;

const check = (label, got, want) => {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) process.exitCode = 1;
  console.log(`${ok ? "PASS" : "FAIL"}  ${label}${ok ? "" : `  got=${JSON.stringify(got)} want=${JSON.stringify(want)}`}`);
};
const q = async (db, sql) => (await db.query(sql)).rows;

async function run(label, legacy) {
  console.log(`\n== ${label}`);
  const db = new PGlite();
  await db.exec(STUBS);
  if (legacy) await db.exec(LEGACY);
  await db.exec(migration);
  await db.exec(migration); // must be re-runnable
  await db.exec(`grant all on all tables in schema public to anon, authenticated, service_role;
    revoke update on public.profiles from authenticated; grant update (full_name) on public.profiles to authenticated;
    grant all on storage.objects to authenticated; grant usage on all sequences in schema storage to authenticated;`);
  console.log("PASS  migration applied twice");

  const asRole = async (role, uid, sql) => {
    await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid ?? ""}', false); set role ${role};`);
    try { return await q(db, sql); } catch (e) { return `ERROR: ${e.message}`; } finally { await db.exec("reset role;"); }
  };

  if (legacy) {
    check("legacy rows kept", await q(db, `select count(*)::int n from "Data"`), [{ n: 2 }]);
    check("legacy device values kept", await q(db, `select "Color_1", "IF_model" from "Devices" where "Device_id"=1`), [{ Color_1: "#FF0000", IF_model: "wb_1" }]);
    check("new columns added", await q(db, `select kind, farm_id from "Devices" where "Device_id"=3`), [{ kind: "tracker", farm_id: null }]);
    check("legacy rows start unscored", await q(db, `select count(*)::int n from "Data" where scored_at is null`), [{ n: 2 }]);
    check("existing user got a profile", await q(db, `select full_name, role::text from profiles`), [{ full_name: "Early User", role: "farmer" }]);
    check("assigned model registered", await q(db, `select name, device_ids from ml_models`), [{ name: "wb_1", device_ids: [1] }]);
    check("old open policies removed", await q(db, `select policyname from pg_policies where tablename in ('Data','Devices') order by 1`),
      [{ policyname: "data_select" }, { policyname: "devices_admin_write" }, { policyname: "devices_select" }]);
    check("anon can no longer read Data", await asRole("anon", null, `select count(*)::int n from "Data"`), [{ n: 0 }]);
    check("anon can no longer insert Data", String(await asRole("anon", null, `insert into "Data" ("Device_id","Timestamp","Latitude","Longitude") values (1, now(), 0, 0)`)).includes("row-level security"), true);

    const A = "00000000-0000-0000-0000-0000000000aa";
    await db.exec(`update profiles set role='admin' where id='${A}'`);
    check("promoted admin sees legacy data", await asRole("authenticated", A, `select count(*)::int n from "Data"`), [{ n: 2 }]);
    await db.exec("set role service_role;");
    check("service role (bridge) can insert", (await q(db, `insert into "Data" ("Device_id","Timestamp","Latitude","Longitude") values (1, now(), 0, 0) returning "Anomaly"`)), [{ Anomaly: 1 }]);
    await db.exec("reset role;");
  } else {
    check("fresh: tables exist", await q(db, `select count(*)::int n from information_schema.tables where table_schema='public' and table_name in ('Devices','Data','profiles','farms','farm_members','scans','ml_models','ml_jobs')`), [{ n: 8 }]);
  }
}

await run("Original Watchbird project (upgrade)", true);
await run("Fresh project", false);
